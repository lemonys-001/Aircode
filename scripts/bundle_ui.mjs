#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();

function toByteArrayDecl(varName, filePath) {
  const buf = fs.readFileSync(filePath);
  const chunks = [];
  for (let i = 0; i < buf.length; i += 20) {
    const slice = buf.subarray(i, Math.min(i + 20, buf.length));
    chunks.push("  " + Array.from(slice).map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", "));
  }
  return `inline constexpr unsigned char ${varName}[] = {\n${chunks.join(",\n")}\n};\ninline constexpr size_t ${varName}_LEN = ${buf.length};\n`;
}

const outHeader = [
  "#pragma once",
  "// Auto-generated by scripts/bundle_ui.mjs — DO NOT EDIT MANUALLY",
  "#include <cstddef>",
  "",
  "namespace aircode {",
  "",
  toByteArrayDecl("EMBEDDED_INDEX_HTML", path.join(root, "ui", "index.html")),
  toByteArrayDecl("EMBEDDED_STYLES_CSS", path.join(root, "ui", "styles.css")),
  toByteArrayDecl("EMBEDDED_APP_JS", path.join(root, "ui", "app.js")),
  "} // namespace aircode",
  ""
].join("\n");

const outPath = path.join(root, "native-win32", "include", "embedded_ui.hpp");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, outHeader, "utf8");
console.log(`Bundled UI assets -> ${outPath} (${(Buffer.byteLength(outHeader) / 1024).toFixed(1)} KB C++ header)`);
